import { NextRequest, NextResponse } from "next/server";
import { getSession } from "@/lib/auth";
import { db } from "@/lib/db";

// GET: Fetch hardware tags, verify pre-generated codes, or list available unassigned stock
export async function GET(req: NextRequest) {
  try {
    const session = await getSession();
    if (!session) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const { searchParams } = new URL(req.url);
    const action = searchParams.get("action");
    const isElevated = session.role === "SUPER_ADMIN" || session.role === "AGENT" || session.role === "FIELD_AGENT";

    // 1. Verify a pre-generated tag code before configuring
    if (action === "verify") {
      const tagCode = searchParams.get("tagCode")?.trim().toUpperCase();
      if (!tagCode) {
        return NextResponse.json({ error: "Tag Code required for verification" }, { status: 400 });
      }

      const tag = await db.smartTag.findUnique({
        where: { tagCode },
        include: {
          business: {
            select: { id: true, name: true, slug: true, city: true },
          },
        },
      });

      if (!tag) {
        return NextResponse.json({
          valid: false,
          error: `Tag "${tagCode}" was not found in inventory. Only Master Admin can mint and generate hardware tags.`,
        });
      }

      if (tag.status === "ASSIGNED" && tag.business) {
        return NextResponse.json({
          valid: false,
          isAssigned: true,
          tag,
          error: `Tag "${tagCode}" is already configured for "${tag.business.name}".`,
        });
      }

      return NextResponse.json({
        valid: true,
        isAssigned: false,
        tag,
        message: `Verified: Pre-generated by Master Admin (${tag.batchCode}) and ready for field configuration.`,
      });
    }

    // 2. Fetch list of available pre-generated tags in stock (unassigned)
    if (action === "in-stock") {
      const inStockTags = await db.smartTag.findMany({
        where: { status: "UNASSIGNED" },
        select: {
          id: true,
          tagCode: true,
          batchCode: true,
          type: true,
          status: true,
          createdAt: true,
        },
        orderBy: { createdAt: "desc" },
        take: 50,
      });

      return NextResponse.json({
        inStock: inStockTags,
        totalInStock: inStockTags.length,
      });
    }

    // 3. Default: Fetch tags assigned to a specific business
    const requestedBizId = searchParams.get("businessId");
    let businessId = session.businessId;
    if (isElevated && requestedBizId) {
      businessId = requestedBizId;
    } else if (!businessId) {
      const first = await db.business.findFirst({ orderBy: { createdAt: "desc" } });
      businessId = first?.id || null;
    }

    if (!businessId) {
      return NextResponse.json({ tags: [] });
    }

    const tags = await db.smartTag.findMany({
      where: { businessId },
      orderBy: { assignedAt: "desc" },
    });

    return NextResponse.json({ tags });
  } catch (err: any) {
    console.error("GET /api/dashboard/tags error:", err);
    return NextResponse.json({ error: "Failed to fetch hardware tags" }, { status: 500 });
  }
}

// POST: Configure / bind a pre-generated hardware standee (NFC + QR) in the field
export async function POST(req: NextRequest) {
  try {
    const session = await getSession();
    if (!session) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const body = await req.json();
    const { tagCode, label, businessId: customBizId } = body;

    if (!tagCode || typeof tagCode !== "string") {
      return NextResponse.json({ error: "Pre-generated Tag Code is required (e.g. TAG-D6D6EE)" }, { status: 400 });
    }

    const cleanCode = tagCode.trim().toUpperCase();

    // Verify tag was pre-generated by Master Admin
    const existingTag = await db.smartTag.findUnique({
      where: { tagCode: cleanCode },
      include: { business: true },
    });

    if (!existingTag) {
      return NextResponse.json({
        error: `Hardware Tag "${cleanCode}" was not found in system inventory. Only Master Admin can generate QR/NFC hardware tags. Please request Master Admin to mint a hardware batch.`,
      }, { status: 404 });
    }

    if (existingTag.status === "ASSIGNED" && existingTag.businessId) {
      return NextResponse.json({
        error: `Hardware Tag "${cleanCode}" is already activated for "${existingTag.business?.name || "another client"}".`,
      }, { status: 400 });
    }

    // Determine target business
    const isElevated = session.role === "SUPER_ADMIN" || session.role === "AGENT" || session.role === "FIELD_AGENT";
    let targetBizId = session.businessId;

    if (isElevated && customBizId) {
      targetBizId = customBizId;
    } else if (!targetBizId) {
      const first = await db.business.findFirst({ orderBy: { createdAt: "desc" } });
      targetBizId = first?.id || null;
    }

    if (!targetBizId) {
      return NextResponse.json({ error: "Please select a target client business to bind this pre-generated standee to." }, { status: 400 });
    }

    const business = await db.business.findUnique({
      where: { id: targetBizId },
    });

    if (!business) {
      return NextResponse.json({ error: "Client business not found" }, { status: 404 });
    }

    // Agent identity formatting
    const roleLabel =
      session.role === "FIELD_AGENT"
        ? "Field Agent"
        : session.role === "AGENT"
        ? "Sales Agent"
        : session.role === "SUPER_ADMIN"
        ? "Super Admin"
        : "Business Admin";

    const agentIdentifier = session.name ? `${session.name} (${roleLabel})` : `${session.email} (${roleLabel})`;

    // Configure the pre-generated hardware tag
    const configuredTag = await db.smartTag.update({
      where: { id: existingTag.id },
      data: {
        businessId: business.id,
        status: "ASSIGNED",
        assignedAt: new Date(),
        assignedBy: agentIdentifier,
        label: label && label.trim() ? label.trim() : (existingTag.label || "Countertop Standee"),
      },
      include: {
        business: {
          select: { id: true, name: true, slug: true, city: true },
        },
      },
    });

    return NextResponse.json({
      success: true,
      message: `Pre-generated standee "${cleanCode}" (${existingTag.batchCode}) successfully configured and bound to "${business.name}" by ${agentIdentifier}!`,
      tag: configuredTag,
      reviewUrl: `/r/${business.slug}`,
    });
  } catch (err: any) {
    console.error("POST /api/dashboard/tags error:", err);
    return NextResponse.json({ error: err.message || "Failed to configure pre-generated hardware tag" }, { status: 500 });
  }
}
